package org.jdbscript.impl.sql;

import org.jdbscript.DBMSType;
import org.jdbscript.utils.TestConfiguration;
import org.testng.SkipException;
import org.testng.annotations.AfterMethod;
import org.testng.annotations.BeforeClass;
import org.testng.annotations.BeforeMethod;
import org.testng.annotations.Test;

import java.lang.reflect.Field;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

public class H2StrategyTest {

    private final H2Strategy strategy = new H2Strategy();
    private Connection cnn;

    @BeforeClass
    public void skipUnlessH2Profile() {
        if (new TestConfiguration().getExpectedDbmsType() != DBMSType.H2) {
            throw new SkipException("H2 strategy tests only run in the h2 profile.");
        }
    }

    @BeforeMethod
    public void openDatabase() throws SQLException {
        cnn = DriverManager.getConnection("jdbc:h2:mem:h2StrategyTest;DB_CLOSE_DELAY=-1", "sa", "sa");
        execute("DROP ALL OBJECTS");
    }

    @AfterMethod
    public void closeDatabase() throws SQLException {
        cnn.close();
    }

    @Test
    public void sqlScriptExecutor_should_use_H2Strategy_for_h2_dbms() throws Exception {
        SqlScriptExecutor executor = new SqlScriptExecutor();
        executor.setDbmsType(DBMSType.H2);

        Field strategyField = SqlScriptExecutor.class.getDeclaredField("strategy");
        strategyField.setAccessible(true);

        assertThat(strategyField.get(executor)).isInstanceOf(H2Strategy.class);
    }

    @Test
    public void resetSequences_should_restart_a_standalone_sequence_at_10000() throws SQLException {
        execute("CREATE SEQUENCE seq");
        nextValue("seq");

        strategy.resetSequences(cnn, List.of());

        assertThat(nextValue("seq")).isEqualTo(10000L);
    }

    @Test
    public void resetSequences_should_restart_an_identity_column_of_a_cleaned_table_at_10000() throws SQLException {
        execute("CREATE TABLE items (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(10))");
        execute("INSERT INTO items (name) VALUES ('a')");
        execute("DELETE FROM items");

        strategy.resetSequences(cnn, List.of("items"));

        assertThat(insertAndGetId("INSERT INTO items (name) VALUES ('b')")).isEqualTo(10000L);
    }

    @Test
    public void resetSequences_should_not_restart_an_identity_column_outside_the_cleaned_tables() throws SQLException {
        execute("CREATE TABLE items (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(10))");
        execute("INSERT INTO items (name) VALUES ('a')");

        strategy.resetSequences(cnn, List.of("other_table"));

        assertThat(insertAndGetId("INSERT INTO items (name) VALUES ('b')")).isEqualTo(2L);
    }

    @Test
    public void resetSequences_should_handle_quoted_mixed_case_names() throws SQLException {
        execute("CREATE SEQUENCE \"MixedSeq\"");
        execute("CREATE TABLE \"MixedItems\" (\"Id\" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"Name\" VARCHAR(10))");
        nextValue("\"MixedSeq\"");

        strategy.resetSequences(cnn, List.of("MixedItems"));

        assertThat(nextValue("\"MixedSeq\"")).isEqualTo(10000L);
        assertThat(insertAndGetId("INSERT INTO \"MixedItems\" (\"Name\") VALUES ('a')")).isEqualTo(10000L);
    }

    private void execute(String sql) throws SQLException {
        try (Statement stmt = cnn.createStatement()) {
            stmt.execute(sql);
        }
    }

    private long nextValue(String sequenceName) throws SQLException {
        try (Statement stmt = cnn.createStatement(); ResultSet rs = stmt.executeQuery("VALUES NEXT VALUE FOR " + sequenceName)) {
            rs.next();
            return rs.getLong(1);
        }
    }

    private long insertAndGetId(String sql) throws SQLException {
        try (Statement stmt = cnn.createStatement()) {
            stmt.executeUpdate(sql, Statement.RETURN_GENERATED_KEYS);
            try (ResultSet rs = stmt.getGeneratedKeys()) {
                rs.next();
                return rs.getLong(1);
            }
        }
    }
}
